### ADIM 02 — TEMATİK İLKE + KARŞIT İLKE TESTİ (Zorunlu + v5.1.3)
* **Tematik İlke:** **Emeğin ve Mülkiyetin Dokunulmazlığı İlkesi (Hıfzu'l-Mâl).** Ekonomik güvenliğin, alın terinin ve kamu düzeninin korunması için suçun kazanç kapısı olmaktan çıkarılması; maksimum caydırıcılık.
* **Karşıt İlke Testi (v5.1.3):**
  - *Karşıt İlke / Gerilim:* **Mülkiyet Güvenliği ve Caydırıcılık (Hıfzu'l-Mâl) ↔ Yaşama Hakkı, Sosyal Adalet ve İnsan Onuru (Keramet).**
  - *Gerilimin Çözümü (Bölüm 19):* Canın ve temel yaşamın korunması (def'-i mefsede), malın korunmasından öncedir. Eğer bir hırsızlık açlıktan veya çaresizlikten kaynaklanıyorsa, suç hırsızın değil, onu aç bırakan toplumun ve devletindir (Hz. Ömer'in içtihadı). Bu durumda had düşer, sosyal yardım ve ıslah devreye girer. Had ancak refah ortamında, doymak bilmez açgözlülükle organize suç işleyenlere uygulanabilir.
  - *Feda Edilen Taraf / Bedel (Trade-off):* Katı şekilci metin uygulaması feda edilir; bedeli, sosyal devletin finansal ve kurumsal yükümlülük altına girmesidir.

